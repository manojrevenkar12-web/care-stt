"""Render results/metrics.json into results/report.md and charts."""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "results"
# Validated categorical order (blue, orange, aqua); text stays in neutral ink.
SERIES = {"tiny": "#2a78d6", "base": "#eb6834", "small": "#1baf7a"}
INK, INK2, GRID = "#0b0b0b", "#52514e", "#e4e3df"
COND_LABEL = {"clean": "Clean", "babble_10": "Babble\n10 dB", "babble_5": "Babble\n5 dB",
              "reverb": "Reverb", "telephone": "Phone\n(GSM)", "opus_8k": "Opus\n8 kbit/s",
              "combined": "Reverb+babble\n+Opus"}


def pct(x) -> str:
    return "–" if x != x else f"{100 * x:.1f}%"


def _style(ax, title, ylabel):
    ax.set_title(title, loc="left", fontsize=11, color=INK, pad=24)
    ax.set_ylabel(ylabel, color=INK2, fontsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=8, length=0)


def grouped_bars(results, metric_path, title, ylabel, fname, int8_only=True):
    test = results["test"]
    order = {"tiny": 0, "base": 1, "small": 2}
    models = sorted((m for m in test if m.endswith("int8") or not int8_only), key=lambda m: order[m.split("-")[0]])
    conds = [c for c in COND_LABEL if all(c in test[m] for m in models)]
    fig, ax = plt.subplots(figsize=(9, 3.6), dpi=150)
    w = 0.8 / len(models)
    for i, m in enumerate(models):
        vals = []
        for c in conds:
            v = test[m][c]
            for k in metric_path:
                v = v[k]
            vals.append(100 * v)
        xs = [j + (i - (len(models) - 1) / 2) * w for j in range(len(conds))]
        ax.bar(xs, vals, width=w * 0.92, color=SERIES[m.split("-")[0]], label=m.replace("-int8", " (int8)"))
    ax.set_xticks(range(len(conds)))
    ax.set_xticklabels([COND_LABEL[c] for c in conds])
    _style(ax, title, ylabel)
    ax.legend(frameon=False, fontsize=8, labelcolor=INK2, ncol=len(models), loc="lower left",
              bbox_to_anchor=(0, 1.0), borderaxespad=0.2)
    fig.tight_layout()
    fig.savefig(OUT / fname)
    plt.close(fig)


def write_report(results: dict) -> None:
    test = results["test"]
    tun = results["threshold_tuning"]
    L = ["# Benchmark report", "",
         "Generated by `scripts/evaluate.py` from `results/metrics.json`. Test split only: "
         "81 held-out sentences x 2 held-out voices = 162 utterances per condition.", ""]

    L += ["## Accuracy by condition (raw transcript)", "",
          "| Model | Condition | WER | CER | Term recall | Number recall | Utts with all numbers right |",
          "|---|---|---|---|---|---|---|"]
    for m, conds in test.items():
        for c, r in conds.items():
            a = r["raw"]
            L.append(f"| {m} | {c} | {pct(a['wer'])} | {pct(a['cer'])} | {pct(a['term_recall'])} | "
                     f"{pct(a['number_recall'])} | {pct(a['number_utt_acc'])} |")

    L += ["", f"## Lexicon post-correction (threshold {tun['chosen']}, tuned on dev to ≥{int(100 * tun['target_precision'])}% precision)", "",
          "| Model | Condition | Term recall raw → corrected | WER raw → corrected | Corrections | Precision |",
          "|---|---|---|---|---|---|"]
    for m, conds in test.items():
        for c, r in conds.items():
            a, b, k = r["raw"], r["corrected"], r["corrections"]
            L.append(f"| {m} | {c} | {pct(a['term_recall'])} → {pct(b['term_recall'])} | "
                     f"{pct(a['wer'])} → {pct(b['wer'])} | {k['applied']} | {pct(k['precision'])} |")

    L += ["", "## Structured extraction (vitals + doses), after correction", "",
          "Field accuracy = value extracted and exactly right. Silent error = wrong value written "
          "without a review flag (the dangerous case). Caught = share of wrong values whose note was flagged.", "",
          "| Model | Condition | Field accuracy | Silent error rate | Wrong values caught | Notes sent to review |",
          "|---|---|---|---|---|---|"]
    for m, conds in test.items():
        for c, r in conds.items():
            e = r["extraction_corrected"]
            L.append(f"| {m} | {c} | {pct(e['field_accuracy'])} | {pct(e['silent_error_rate'])} | "
                     f"{pct(e['wrong_caught_share'])} | {pct(e['review_rate'])} |")

    L += ["", "## 95% bootstrap confidence intervals (clean, 1,000 resamples of utterances)", "",
          "| Model | WER | Term recall raw | Term recall corrected | Gain from correction (paired) |",
          "|---|---|---|---|---|"]
    for m, conds in test.items():
        ci = conds.get("clean", {}).get("ci95")
        if ci:
            f = lambda k: f"{pct(ci[k][0])} – {pct(ci[k][1])}"  # noqa: E731
            L.append(f"| {m} | {f('wer')} | {f('term_recall')} | {f('term_recall_corrected')} | {f('term_recall_gain')} |")

    L += ["", "## Deployment trade-off (idle machine, 30 clean clips, mean 4 s audio)", "",
          "Measured by `scripts/latency.py` on a 2-vCPU cloud VM after a warm-up decode.", "",
          "| Model | Size (MB) | WER (clean) | Threads | Decode p50 (s) | Decode p95 (s) | Real-time factor |",
          "|---|---|---|---|---|---|---|"]
    for key, lat in sorted(results.get("latency_idle", {}).items()):
        m = lat["model"]
        wer = pct(test[m]["clean"]["raw"]["wer"]) if m in test and "clean" in test[m] else "–"
        L.append(f"| {m} | {lat['size_mb']} | {wer} | {lat['threads']} | {lat['decode_p50_s']} | "
                 f"{lat['decode_p95_s']} | {lat['rtf_mean']} |")

    L += ["", "## Per test voice (clean)", "", "| Model | Voice | WER | Term recall | Number recall |", "|---|---|---|---|---|"]
    for m, voices in results.get("per_voice_clean", {}).items():
        for v, a in voices.items():
            L.append(f"| {m} | {v} | {pct(a['wer'])} | {pct(a['term_recall'])} | {pct(a['number_recall'])} |")

    L += ["", "## Threshold sweep (dev)", "", "| Threshold | Good | Bad | Precision |", "|---|---|---|---|"]
    for s in tun["sweep"]:
        L.append(f"| {s['threshold']} | {s['good']} | {s['bad']} | {pct(s['precision'])} |")
    (OUT / "report.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    grouped_bars(results, ["raw", "wer"], "Word error rate by acoustic condition (lower is better)",
                 "WER (%)", "wer_by_condition.png")
    grouped_bars(results, ["raw", "number_utt_acc"],
                 "Utterances with every number exactly right (higher is better)",
                 "Utterances (%)", "numbers_by_condition.png")
    before_after(results, "small-int8")


def before_after(results, model):
    """Term recall raw vs after lexicon correction, one model, all conditions."""
    conds = [c for c in COND_LABEL if c in results["test"][model]]
    raw = [100 * results["test"][model][c]["raw"]["term_recall"] for c in conds]
    cor = [100 * results["test"][model][c]["corrected"]["term_recall"] for c in conds]
    fig, ax = plt.subplots(figsize=(9, 3.6), dpi=150)
    xs = range(len(conds))
    ax.bar([x - 0.2 for x in xs], raw, width=0.37, color="#2a78d6", label="Whisper output")
    ax.bar([x + 0.2 for x in xs], cor, width=0.37, color="#eb6834", label="+ lexicon correction")
    for x, r, c in zip(xs, raw, cor):
        if c - r >= 5:
            ax.annotate(f"+{c - r:.0f}", (x + 0.2, c), ha="center", va="bottom", fontsize=8, color=INK2,
                        xytext=(0, 2), textcoords="offset points")
    ax.set_xticks(list(xs))
    ax.set_xticklabels([COND_LABEL[c] for c in conds])
    _style(ax, f"Drug & nursing-term recall, {model} (higher is better)", "Term recall (%)")
    ax.legend(frameon=False, fontsize=8, labelcolor=INK2, ncol=2, loc="lower left", bbox_to_anchor=(0, 1.0),
              borderaxespad=0.2)
    fig.tight_layout()
    fig.savefig(OUT / "terms_by_condition.png")
    plt.close(fig)
